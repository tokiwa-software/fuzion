  /**
   * Helper method used by _removedIntrinsics for
   * {@code autogenerated_code_for_Open_Types_fold} and
   * {@code autogenerated_code_for_effect_types_fold} to create the actual inline
   * code.
   *
   * @param call to the {@code autogenerated_code_for...} method we are creating code
   * for.
   *
   * @param currentClazz the surrounding clazz that performs the call.
   *
   * @param types the types that are to be folded
   *
   * @return the actual code
   */
  private static Expr codeForTypeFold(AbstractCall call,
                                      Clazz currentClazz,
                                      List<AbstractType> types)
  {
    Expr effect = call.actuals().get(0);
    var aa = call.actuals().get(1);
    for (var t : types)
      {
        var ta = currentClazz.actualTypeParameters()[1];
        var apply = ta.lookup(new FeatureAndActuals((LibraryFeature)Types.resolved.f_type_applicator_apply,
                                                    new List<>(t)),
                              FuzionConstants.NO_SELECT,
                              false /* isInheritanceCall */);
        var fe = effect; // effectively final copy of effect
        effect = new AbstractCall()                                // e.g. aa.apply <type of tuple.values.3> e
          {
            @Override public SourcePosition     pos()                  { return call.pos(); }
            @Override public Expr               target()               { return aa; }
            @Override public AbstractFeature    calledFeature()        { return apply.feature(); }
            @Override public List<AbstractType> actualTypeParameters() { return new List<>(t); }
            @Override public List<Expr>         actuals()              { return new List<>(fe); }
            @Override public AbstractType       type()                 { return fe.type(); }
          };
      }
    return effect;
  }

