  int addCode(int cl, Clazz c)
  {
    var code = new List<Object>();
    var inhe = new List<List<AbstractCall>>();
    addCode(cl, c, code, inhe, c.feature(), AbstractCall.NO_CALLS /* no inheritance */);
    check
      (code.size() == inhe.size(),
       _allCode.size() == _inh.size());
    var result = addCode(code);
    _inh.addAll(inhe);
    _inh.add(null);
    check
      (_allCode.size() == _inh.size());
    while (_siteClazzes.size() < _allCode.size())
      {
        _siteClazzes.add(cl);
      }
    check
      (_allCode.size() == _siteClazzes.size());
    return result;
  }

  void addCode(int cl, Clazz c, List<Object> code, List<List<AbstractCall>> inhe, FuirFeature ff, List<AbstractCall> inh)
  {
    var ocur = _currentClazz;
    if (CHECKS) check
      (_currentClazz == null || _currentClazz == c); /* make sure no recursive call changes this */
    _currentClazz = c;
    if (!clazzIsVoidType(cl))
      {
        for (var p: ff.inherits())
          {
            var pf = p.calledFeature();
            var of = pf.outerRef();
            Clazz or = (of == null) ? null : c.lookup(of);
            var needsOuterRef = outerRefNeeded(or);
            toStack(code, p.target(), !needsOuterRef /* dump result if not needed */, false);
            if (needsOuterRef)
              {
                code.add(ExprKind.Current);
                code.add(or);  // field clazz means assignment to field
              }
            if (CHECKS) check
              (p.actuals().size() == p.calledFeature().valueArguments().size());

            AbstractFeature cf = pf;
            var n = p.actuals().size();
            var argFields = new Clazz[n];
            for (var i = 0; i < n; i++)
              {
                if (i >= cf.valueArguments().size())
                  {
                    if (CHECKS) check
                      (Errors.any());
                  }
                else
                  {
                    var cfa = (FuirFeature) cf.valueArguments().get(i);
                    argFields[i] = c.lookupNeeded(cfa);
                  }
              }
            var fat = p.formalArgumentTypes();
            for (var i = 0; i < p.actuals().size(); i++)
              {
                var a = p.actuals().get(i);
                toStack(code, boxAndTag(a, fat[i]));
                code.add(ExprKind.Current);
                // Field clazz means assign value to that field
                code.add(argFields[i]);
              }

            while (inhe.size() < code.size()) { inhe.add(inh); }
            while (_inh.size() < _allCode.size()) { _inh.add(inh); }
            var inh1 = new List<AbstractCall>();
            inh1.add(p);
            inh1.addAll(inh);
            addCode(cl, c, code, inhe, pf, inh1);
          }
        toStack(code, ff.code());
        while (inhe.size() < code.size()) { inhe.add(inh); }
        while (_inh.size() < _allCode.size()) { _inh.add(inh); }
      }
    if (CHECKS) check
      (_currentClazz == c); /* make sure no recursive call accidentally changed this */
    _currentClazz = ocur;
  }

