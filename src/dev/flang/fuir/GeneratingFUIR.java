  /**
   * Find the redefinition of feature f within heir.
   *
   * @param heir a feature that inherits from f.outer(), directly or
   *             indirectly.
   *
   * @param f    a feature declared in or inherited by f.outer()
   *
   * @return the feature in heir that redefines f, or f itself if f is not
   *         redefined in heir.
   */
  AbstractFeature findRedefinition(AbstractFeature heir, AbstractFeature f) {
    if (PRECONDITIONS) require
      (// type parameters never get redefined, they are effectively fixed.
       // However, type features get replaced by actual type parameters in the
       // inheritance call. Instead of searching for the redefinition, the type
       // should be replaced by the actual type.
       !f.isTypeParameter()
       // NYI CLEANUP: this should be possible?: ,!_lookupDone
      );

    var result = _redefinitionLookup.findRedefinition(heir, f);

    if (POSTCONDITIONS) ensure
      (result != null);

    return result;
  }


  /**
   * Determine the result clazz of an Expr.
   *
   * @param inh the inheritance chain that brought the code here (in case it is
   * an inlined inherits call).
   */
  Clazz clazz(Expr e, Clazz outerClazz, List<AbstractCall> inh)
  {
    Clazz result;
    if (e instanceof AbstractBlock b)
      {
        Expr resExpr = b.resultExpression();
        if (CHECKS) check
          (resExpr != null);
        result = clazz(resExpr, outerClazz, inh);
      }

    else if (e instanceof Box b)
      {
        result = outerClazz.handDown(b.type(), inh);
      }

    else if (e instanceof AbstractCall c)
      {
        var tclazz = clazz(c.target(), outerClazz, inh);
        if (!tclazz.isVoidType())
          {
            var at = AbstractFeature.handDownListThroughInheritsCalls(c.actualTypeParameters(), inh);
            var typePars = outerClazz.actualGenerics(at, inh);
            result = tclazz.lookupCall(c, typePars).resultClazz();
          }
        else
          {
            result = tclazz;
          }
      }

    else if (e instanceof AbstractCurrent)
      {
        result = outerClazz;
      }

    else if (e instanceof AbstractMatch m)
      {
        result = outerClazz.handDown(m.type(), inh);
      }

    else if (e instanceof Universe)
      {
        result = clazz(_universe);
      }

    else if (e instanceof Constant c)
      {
        result = outerClazz.handDown(c.type(), inh);
      }

    else if (e instanceof Tag tg)
      {
        result = outerClazz.handDown(tg._taggedType, inh);
      }

    else if (e instanceof InlineArray ia)
      {
        result = outerClazz.handDown(ia.type(), inh);
      }

    else
      {
        if (!Errors.any())
          {
            throw new Error("" + e + " "+ e.getClass() + " should no longer exist at runtime");
          }

        result = error();
      }

    if (POSTCONDITIONS) ensure
      (result != null);

    return result;
  }


