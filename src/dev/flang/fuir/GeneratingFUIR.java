  /**
   * Add entries of type ExprKind created from the given expression (and its
   * nested expressions) to list l. pop the result in case dumpResult==true.
   *
   * @param stack the work stack for the nested expressions.
   *
   * @param l list of ExprKind that should be extended by s's expressions
   *
   * @param e a expression.
   *
   * @param dumpResult flag indicating that we are not interested in the result.
   */
  @Override
  protected void toStack(ArrayDeque<Runnable> stack, List<Object> l, Expr e, boolean dumpResult)
  {
    if (isConst(e) && !dumpResult)
      {
        l.add(e.asCompileTimeConstant());
      }
    else
      {
        if (e instanceof AbstractCall call)
          {
            var cf = call.calledFeature();
            var qn = cf.qualifiedName();
            if (cf.isIntrinsic() && _removedIntrinsics_.containsKey(qn))
              {
                e = _removedIntrinsics_.get(qn).code(call, _currentClazz, this);
              }
            else if (cf.isOpenTypeParameter())
              {
                var t = call.target();
                var op = cf.openTypesFeature();
                var cur = _currentClazz;
                Expr target = new Current(call.pos(), cur.feature());
                while (!cur.feature().inheritsFrom(cf.outer()))
                  {
                    var ft = target;
                    var fcur = cur;
                    target = new AbstractCall()
                      {
                        @Override public SourcePosition     pos()                  { return call.pos(); }
                        @Override public Expr               target()               { return ft; }
                        @Override public AbstractFeature    calledFeature()        { return fcur.feature().outerRef(); }
                        @Override public AbstractType       type()                 { return fcur.feature().outerRef().resultType(); }
                      };
                    cur = cur._outer;
                  }
                var ft = target;
                var fcur = cur;
                var replacement = new AbstractCall()   // e.g. tuple.#Values_Of_Open_Type<n>
                  {
                    @Override public SourcePosition     pos()                  { return call.pos(); }
                    @Override public Expr               target()               { return ft; }
                    @Override public AbstractFeature    calledFeature()        { return op; }
                    @Override public AbstractType       type()                 { return fcur.replaceThisType(op.resultType()); }
                  };
                stack.push(() -> toStack(stack, l, replacement, dumpResult));
                stack.push(() -> toStack(stack, l, t, true));   // we must evaluate `t` since strange code structure like #5816 could have side-effects
                return;
              }
          }
        super.toStack(stack, l, e, dumpResult);
      }
  }


  /**
   * Is this a compile-time constant?
   *
   * @param o an Object from the IR-Stack.
   *
   * @return true iff {@code o} is an Expr and can be turned into a compile-time constant.
   */
  private boolean isConst(Object o)
  {
    return o instanceof InlineArray iai && isConst(iai)
        || o instanceof Constant
        || o instanceof AbstractCall ac && isConst(ac)
        || o instanceof AbstractBlock ab && ab._expressions.size() == 1 && isConst(ab.resultExpression());
  }


  /**
   * Can this array be turned into a compile-time constant?
   */
  private boolean isConst(InlineArray ia)
  {
    return !ia.type().dependsOnGenerics()
      && ia.type().containsThisType()
      // some backends have special handling for array void.
      && !ia.elementType().isVoid()
      && ia._elements
        .stream()
        .allMatch(el -> {
          var s = new List<>();
          // NYI: CLEANUP: unexpected sideEffect of isConst
          toStack(s, el);
          return s
            .stream()
            .allMatch(x -> isConst(x));
        })
      // NYI: UNDER DEVELOPMENT: remove this restriction?
      && ia._elements.stream().allMatch(x -> ia.elementType().isAssignableFromDirectly(x.type()).yes());
  }


  /**
   * Can this call be turned into a constant?
   *
   * @param ac the call to be analyzed.
   *
   * @return true iff the call is suitable to be turned into
   * a compile time constant.
   */
  private boolean isConst(AbstractCall ac)
  {
    if (ac._isConst == YesNo.dontKnow)
      {
        var result =
          ac.calledFeature().kind() == Kind.Constructor &&
          // contains no fields
          ac.calledFeature().code().containsOnlyDeclarations() &&
          // only features without args and no fields may be inherited
          // NYI: UNDER DEVELOPMENT: we could relax this more
          ac.calledFeature().inherits().stream().allMatch(c -> isConst(c) || c.calledFeature().isUnitTypeWithoutSideEffect(true)) &&
          // NYI: UNDER DEVELOPMENT: support consts with contracts
          ac.calledFeature().contract().isEmpty() &&
          ac.actuals().stream().allMatch(x -> isConst(x));

        if (result)
          {
            var s = new List<>();
            toStack(s, ac, false, true);
            result = s
              .stream()
              .allMatch(x -> x == ac || isConst(x));
          }
        ac._isConst = result ? YesNo.yes : YesNo.no;
      }
    return ac._isConst.yes();
  }




